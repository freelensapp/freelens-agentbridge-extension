// The mark of a provider, or nothing for an id without one; callers keep the
// provider's name beside it, so the mark is always decorative.
export function ProviderMark({ providerId, ...props }: { providerId: string } & SVGProps<SVGSVGElement>) {
  const mark = MARKS[providerId];

  if (!mark) return null;

  return (
    <svg viewBox="0 0 24 24" width="16" height="16" fill="currentColor" fillRule="evenodd" aria-hidden {...props}>
      {mark.paths.map((d) => (
        <path key={d} d={d} clipRule="evenodd" />
      ))}
    </svg>
  );
}
